const KEYS = Object.keys(ADMIN_EN).sort((a, b) => b.length - a.length);

/** Translates every known Hindi phrase inside a piece of admin text. Unknown text stays as it is. */
export function toEnglish(text: string): string {
  if (!/[\u0900-\u097F]/.test(text)) return text;
  const exact = ADMIN_EN[text.trim()];
  if (exact) return text.replace(text.trim(), exact);
  let out = text;
  for (const key of KEYS) {
    if (key.length < 3) continue;
    if (out.includes(key)) out = out.split(key).join(ADMIN_EN[key]!);
    if (!/[\u0900-\u097F]/.test(out)) break;
  }
  return out;
}
